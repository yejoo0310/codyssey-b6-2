def build_commit_prompt(status, diff):
    return f"""
당신은 Git 커밋 메시지를 작성하는 소프트웨어 개발자입니다.

아래 Git 변경 사항을 분석해서 커밋 제목 1줄만 작성하세요.

규칙:
- 반드시 한 줄만 출력하세요.
- 커밋 본문은 작성하지 마세요.
- 설명이나 부가 문구를 작성하지 마세요.
- Conventional Commits 형식을 사용하세요.
- 형식은 반드시 다음과 같아야 합니다.

type: 한글 제목

사용 가능한 type:
- feat: 새로운 기능 추가
- fix: 버그 수정
- docs: 문서 변경
- refactor: 기능 변경 없는 코드 구조 개선
- test: 테스트 코드 추가 또는 수정
- chore: 설정, 빌드, 기타 유지보수 작업

제목 규칙:
- type은 영어로 작성하세요.
- 콜론(:) 뒤의 제목은 반드시 한글로 작성하세요.
- 변경 사항의 핵심을 구체적으로 표현하세요.
- 가능하면 50자 이내로 작성하세요.
- 절대 72자를 넘기지 마세요.
- 실제 Git 변경 사항에 없는 내용을 만들지 마세요.

Git Status:
{status}

Git Diff:
{diff}
""".strip()


def build_pr_prompt(status, diff):
    return f"""
당신은 Git 변경 사항을 분석하여 Pull Request 초안을 작성하는
소프트웨어 개발자입니다.

아래 Git 변경 사항만을 근거로 PR 제목과 본문을 작성하세요.

반드시 다음 형식을 정확히 따르세요.

[PR_TITLE]
PR 제목

[PR_BODY]
## Why
- 내용

## What
- 내용

## How to Test
- 내용

출력 규칙:
- [PR_TITLE]과 [PR_BODY]를 반드시 유지하세요.
- 섹션 이름을 변경하거나 축약하지 마세요.
- 반드시 "## Why", "## What", "## How to Test"를 사용하세요.
- "## How"와 같은 다른 섹션 이름은 사용하지 마세요.
- 위 세 섹션 외의 추가 섹션은 만들지 마세요.
- 설명이나 인사말 없이 결과만 출력하세요.

PR 제목 규칙:
- 반드시 한 줄이어야 합니다.
- 최대 80자를 넘기지 마세요.
- 제목 내용은 한글로 작성하세요.
- 필요한 경우 다음 type을 사용할 수 있습니다.
  feat, fix, docs, refactor, test, chore

본문 규칙:
- Why는 변경 이유 또는 배경을 1~2개의 불릿으로 작성하세요.
- What은 핵심 변경 사항을 2~4개의 불릿으로 작성하세요.
- How to Test는 테스트 방법을 1~3개의 불릿으로 작성하세요.
- 모든 섹션에는 최소 1개의 '-' 불릿이 있어야 합니다.
- 각 불릿은 한 문장으로 간결하게 작성하세요.
- Git 변경 내용에서 확인되지 않는 사실을 만들지 마세요.

Git Status:
{status}

Git Diff:
{diff}
""".strip()